const norm = (emoji: string) => emoji.replace(/️/g, '')
const byKey = new Map(Object.entries(GLYPHS).map(([k, v]) => [norm(k), v]))

export const hasGlyph = (emoji: string) => byKey.has(norm(emoji))

export function Glyph({ emoji, className = 'h-7 w-7', strokeWidth = 1.8 }: { emoji: string; className?: string; strokeWidth?: number }) {
  const paths = byKey.get(norm(emoji))
  if (!paths) return null
  return (
    <svg
      viewBox="0 0 24 24"
      className={`${className} shrink-0 select-none drop-shadow-[0_1px_2px_rgba(0,0,0,0.35)]`}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  )
}
